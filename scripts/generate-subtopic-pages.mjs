// Generates ONE React file per subtopic in src/pages/subtopics/
// Run with: node scripts/generate-subtopic-pages.mjs
// Safe to re-run — it only (re)creates files for subtopics currently in categories.js.
// Edit src/data/categories.js to add/remove subtopics, then re-run this script.

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dataFile = path.join(__dirname, "../src/data/categories.js");
const outDir = path.join(__dirname, "../src/pages/subtopics");

const slugify = (s) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");

// Minimal re-implementation of categories (mirrors src/data/categories.js)
const src = fs.readFileSync(dataFile, "utf-8");
const catMatch = src.match(/export const CATEGORIES = (\[[\s\S]*?\n\]);/);
if (!catMatch) throw new Error("Could not parse CATEGORIES from categories.js");
// eslint-disable-next-line no-new-func
const CATEGORIES = new Function(`return ${catMatch[1]}`)();

fs.mkdirSync(outDir, { recursive: true });

const componentNameFor = (catLabel, group, item) =>
  (catLabel + "_" + group + "_" + item)
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .split(" ")
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("") + "Page";

const highlightBank = [
  { title: "Handpicked Fabric", desc: "Selected for texture, drape and everyday comfort." },
  { title: "Trusted Craftsmanship", desc: "Made with techniques passed down through generations." },
  { title: "Occasion Ready", desc: "Styled to work for festive, formal and everyday wear." },
];

// Five style variants used to build a 5-item collection grid for every subtopic.
const styleBank = ["Classic Weave", "Festive Edit", "Everyday Comfort", "Designer Pick", "New Season"];

let created = 0;
const importLines = [];
const routeLines = [];

for (const cat of CATEGORIES) {
  for (const g of cat.groups) {
    for (const item of g.items) {
      const slug = slugify(item);
      const groupSlug = slugify(g.groupName);
      const compName = componentNameFor(cat.label, g.groupName, item);
      const fileName = `${slugify(cat.label)}__${groupSlug}__${slug}.jsx`;
      const filePath = path.join(outDir, fileName);

      const escapedItem = item.replace(/"/g, '\\"');
      const collectionsBlock = styleBank
        .map(
          (style, i) =>
            `        { id: ${i + 1}, title: "${escapedItem} — ${style}", image: imageFor("${escapedItem}-${i}") },`
        )
        .join("\n");

      const fileContent = `import React from "react";
import SubtopicPageTemplate from "../../components/SubtopicPageTemplate.jsx";
import { imageFor } from "../../data/categories.js";

// EDITABLE PAGE FILE — Category: ${cat.label} > ${g.groupName} > ${item}
// Change the text/collections below to customise this exact page. Each
// collection image can also be swapped live in the browser via its "Edit"
// button (persisted per-browser). The shared layout lives in
// SubtopicPageTemplate.jsx (used by every subtopic page).
export default function ${compName}() {
  // At least 5 collection looks for "${escapedItem}" — add more items here any time.
  const collections = [
${collectionsBlock}
  ];

  return (
    <SubtopicPageTemplate
      name="${escapedItem}"
      category="${cat.label}"
      categorySlug="${cat.slug}"
      group="${g.groupName.replace(/"/g, '\\"')}"
      description="Discover our ${item} collection at Mangalam Silks & Readymades — thoughtfully curated for quality, comfort and timeless style."
      highlights={${JSON.stringify(highlightBank, null, 8).replace(/\n/g, "\n      ")}}
      collections={collections}
    />
  );
}
`;

      fs.writeFileSync(filePath, fileContent);
      created++;

      importLines.push(`import ${compName} from "../pages/subtopics/${fileName}";`);
      routeLines.push(
        `  { path: "/${cat.slug}/${groupSlug}/${slug}", Component: ${compName} },`
      );
    }
  }
}

const manifestContent = `// AUTO-GENERATED by scripts/generate-subtopic-pages.mjs — do not edit by hand.
// Re-run the script after changing src/data/categories.js.
${importLines.join("\n")}

export const SUBTOPIC_ROUTES = [
${routeLines.join("\n")}
];
`;

fs.writeFileSync(path.join(__dirname, "../src/data/subtopicRoutes.js"), manifestContent);

console.log(`Generated ${created} subtopic page files in ${outDir}`);
console.log(`Wrote route manifest to src/data/subtopicRoutes.js`);
